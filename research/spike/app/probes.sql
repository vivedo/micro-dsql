-- Probes for inferred ([I]) claims in research/02 and research/04, and for statements DSQL
-- rejects (research/04 §C says Turso accepts several of them). Labels: P01..P30.
\set VERBOSITY verbose

\echo P01 int4 overflow: arithmetic
SELECT 2147483647::int4 + 1 AS overflow;
\echo P02 int4 overflow: storing 3e9 into an integer column
CREATE TABLE p_int (id int PRIMARY KEY, n int4);
INSERT INTO p_int VALUES (1, 3000000000);
SELECT n FROM p_int;
\echo P03 int2 range check
CREATE TABLE p_small (id int PRIMARY KEY, s smallint);
INSERT INTO p_small VALUES (1, 40000);

\echo P04 bare numeric storage (expected REAL per research/02)
CREATE TABLE p_num (id int PRIMARY KEY, v numeric);
INSERT INTO p_num VALUES (1, 0.1), (2, 0.2), (3, 123456789.123456789);
SELECT sum(v) AS sum_01_02 FROM p_num WHERE id IN (1, 2);
SELECT v FROM p_num WHERE id = 3;

\echo P05 timestamp(p) and char(n)
CREATE TABLE p_ts (id int PRIMARY KEY, t timestamp(3));
CREATE TABLE p_char (id int PRIMARY KEY, c char(10));

\echo P06 interval arithmetic
SELECT interval '1 day' + interval '2 hours' AS iv;
SELECT '2026-01-01 00:00:00+00'::timestamptz + interval '1 month' AS plus_month;

\echo P07 information_schema
SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' ORDER BY 1;
SELECT column_name FROM information_schema.columns WHERE table_name = 'orders' ORDER BY ordinal_position;

\echo P08 pg_catalog introspection
SELECT relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND relkind = 'r' ORDER BY 1;

\echo P09 SELECT ... FOR UPDATE / FOR KEY SHARE
SELECT * FROM products WHERE id = 1 FOR UPDATE;
SELECT * FROM products WHERE id = 1 FOR KEY SHARE;

\echo P10 DELETE ... USING
DELETE FROM order_items oi USING orders o WHERE o.id = oi.order_id AND o.id = 103;

\echo P11 CREATE INDEX ASYNC (DSQL syntax)
CREATE INDEX ASYNC products_price_idx ON products (price);

\echo P12 IDENTITY column
CREATE TABLE p_ident (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v text);

\echo P13 sequence CACHE 65536 vs CACHE 1
CREATE SEQUENCE p_seq_big CACHE 65536;
CREATE SEQUENCE p_seq_one CACHE 1;
SELECT nextval('p_seq_one');

\echo P14 ADD CONSTRAINT ... NOT VALID
ALTER TABLE orders ADD CONSTRAINT orders_total_pos CHECK (total >= 0) NOT VALID;

\echo P15 ALTER COLUMN SET DEFAULT / DROP NOT NULL
ALTER TABLE orders ALTER COLUMN status SET DEFAULT 'new';
ALTER TABLE orders ALTER COLUMN status DROP NOT NULL;

\echo P16 ALTER TABLE ADD COLUMN / RENAME COLUMN
ALTER TABLE orders ADD COLUMN note text;
ALTER TABLE orders RENAME COLUMN note TO remark;

\echo P17 statements DSQL rejects: TRUNCATE, TEMP TABLE, SAVEPOINT, DOMAIN, ENUM, array column, SERIAL, MATERIALIZED VIEW
CREATE TABLE p_trunc (id int PRIMARY KEY);
TRUNCATE p_trunc;
CREATE TEMP TABLE p_temp (id int PRIMARY KEY);
BEGIN;
SAVEPOINT sp1;
ROLLBACK TO SAVEPOINT sp1;
ROLLBACK;
CREATE DOMAIN p_dom AS text CHECK (VALUE <> '');
CREATE TYPE p_mood AS ENUM ('ok', 'meh');
CREATE TABLE p_arr (id int PRIMARY KEY, tags text[]);
CREATE TABLE p_serial (id serial PRIMARY KEY);
CREATE MATERIALIZED VIEW p_mv AS SELECT id FROM products;
CREATE VIEW p_v AS SELECT id, sku FROM products;
SELECT count(*) FROM p_v;

\echo P18 more DSQL-rejected: triggers, functions, extensions, LISTEN/NOTIFY, advisory locks, COPY TO STDOUT
CREATE FUNCTION p_f() RETURNS int LANGUAGE sql AS 'SELECT 1';
CREATE EXTENSION IF NOT EXISTS pgcrypto;
LISTEN chan;
NOTIFY chan;
SELECT pg_advisory_lock(1);
COPY products (id, sku) TO STDOUT;

\echo P19 SET whitelist candidates and SHOW
SET datestyle = 'ISO, MDY';
SET intervalstyle = 'postgres';
SET enable_seqscan = off;
SET statement_timeout = 1000;
SHOW datestyle;
SHOW application_name;

\echo P20 transaction behaviour: error inside txn then 25P02, COMMIT of an aborted txn
BEGIN;
SELECT 1/0;
SELECT 1;
COMMIT;

\echo P21 DDL + DML in one transaction, two DDLs in one transaction (DSQL rejects both)
BEGIN;
CREATE TABLE p_ddl1 (id int PRIMARY KEY);
INSERT INTO p_ddl1 VALUES (1);
CREATE TABLE p_ddl2 (id int PRIMARY KEY);
COMMIT;

\echo P22 multi-statement simple query (implicit transaction?)
CREATE TABLE p_multi (id int PRIMARY KEY);
INSERT INTO p_multi VALUES (1) \; INSERT INTO p_multi VALUES (1) \; INSERT INTO p_multi VALUES (2);
SELECT id FROM p_multi ORDER BY id;

\echo P23 PG18-only syntax: uuidv7(), virtual generated column
SELECT length(uuidv7()::text);
CREATE TABLE p_gen (id int PRIMARY KEY, a int, b int GENERATED ALWAYS AS (a * 2) VIRTUAL);

\echo P24 EXPLAIN
EXPLAIN SELECT * FROM orders WHERE customer_id = '11111111-1111-1111-1111-111111111111';

\echo P25 timestamptz literal forms: short offset "+00" (PG output format) vs "+00:00"; text round trip
SELECT '2026-01-02 03:04:05.123456+00'::timestamptz AS short_offset;
SELECT '2026-01-02 03:04:05+01'::timestamptz AS short_offset_plus1;
SELECT '2026-01-02 03:04:05.123456+00:00'::timestamptz AS long_offset;
SELECT now()::text::timestamptz IS NOT NULL AS own_output_roundtrip;
