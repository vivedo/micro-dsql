//! M3 DDL rules and rewrites through a real client (specs US2, US3, US6): identity and
//! sequences, constraints on existing tables, refused `ALTER TABLE` forms.

use tokio_postgres::Client;

use crate::common::{rows, s, value, TestServer};
use crate::dsql_rules::{e, Proto, PROTOS};

/// The first column of every row of a query, as text, on either protocol.
async fn column(proto: Proto, c: &Client, sql: &str) -> Vec<String> {
    match proto {
        Proto::Simple => rows(c, sql)
            .await
            .into_iter()
            .map(|r| r[0].clone().unwrap_or_default())
            .collect(),
        Proto::Extended => c
            .query(sql, &[])
            .await
            .unwrap_or_else(|e| panic!("{sql}: {e:?}"))
            .iter()
            .map(|r| match r.try_get::<_, i64>(0) {
                Ok(n) => n.to_string(),
                Err(_) => match r.try_get::<_, i32>(0) {
                    Ok(n) => n.to_string(),
                    Err(_) => r.get::<_, String>(0),
                },
            })
            .collect(),
    }
}

async fn sequences(c: &Client, name: &str) -> Option<String> {
    value(
        c,
        &format!("SELECT count(*) FROM pg_sequences WHERE sequencename = '{name}'"),
    )
    .await
}

#[tokio::test]
async fn identity_columns_number_rows() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let t = format!("idn_{proto:?}").to_lowercase();
        proto
            .ok(
                &c,
                &format!(
                    "CREATE TABLE {t} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) \
                     PRIMARY KEY, v text)"
                ),
            )
            .await;
        assert_eq!(
            column(
                proto,
                &c,
                &format!("INSERT INTO {t} (v) VALUES ('x'), ('y') RETURNING id")
            )
            .await,
            ["1", "2"],
            "{proto:?}"
        );
        // BY DEFAULT: an explicit value is stored as given.
        proto
            .ok(&c, &format!("INSERT INTO {t} (id, v) VALUES (50, 'z')"))
            .await;
        assert_eq!(
            column(proto, &c, &format!("SELECT id FROM {t} ORDER BY id")).await,
            ["1", "2", "50"]
        );
        // Sequence options, an explicit sequence name and GENERATED ALWAYS.
        let o = format!("ido_{proto:?}").to_lowercase();
        proto
            .ok(
                &c,
                &format!(
                    "CREATE TABLE {o} (n bigint GENERATED ALWAYS AS IDENTITY (sequence name \
                     \"{o}_numbers\" INCREMENT BY 5 MINVALUE 100 MAXVALUE 1000 START WITH 100 \
                     CACHE 1), v int)"
                ),
            )
            .await;
        assert_eq!(
            column(
                proto,
                &c,
                &format!("INSERT INTO {o} (v) VALUES (1), (2), (3) RETURNING n")
            )
            .await,
            ["100", "105", "110"],
            "{proto:?}"
        );
        assert_eq!(sequences(&c, &format!("{o}_numbers")).await, s("1"));
        // The identity column is NOT NULL.
        assert_eq!(
            proto
                .err(&c, &format!("INSERT INTO {o} (n, v) VALUES (NULL, 9)"))
                .await
                .code,
            "23502",
            "{proto:?}"
        );
    }
}

#[tokio::test]
async fn cached_sequences_number_like_cache_one() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let name = format!("sq_{proto:?}").to_lowercase();
        for (i, cache) in ["65536", "1", "1000000"].into_iter().enumerate() {
            let seq = format!("{name}_{i}");
            proto
                .ok(&c, &format!("CREATE SEQUENCE {seq} CACHE {cache}"))
                .await;
            assert_eq!(
                column(
                    proto,
                    &c,
                    &format!("SELECT nextval('{seq}'), nextval('{seq}')")
                )
                .await,
                ["1"],
                "{proto:?}"
            );
            assert_eq!(value(&c, &format!("SELECT nextval('{seq}')")).await, s("3"));
        }
        proto
            .ok(&c, &format!("ALTER SEQUENCE {name}_0 CACHE 100000"))
            .await;
        proto
            .ok(&c, &format!("ALTER SEQUENCE {name}_0 CACHE 1"))
            .await;
    }
}

#[tokio::test]
async fn dsql_identity_and_sequence_rules_are_enforced() {
    let server = TestServer::start();
    let c = server.connect().await;
    const NEED: &str = "please define CACHE greater than or equal to 65536 or equal to 1";
    for proto in PROTOS {
        assert_eq!(
            proto
                .err(
                    &c,
                    "CREATE TABLE r1 (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"
                )
                .await,
            e(
                "0A000",
                &format!("identity column is not supported without an explicit cache size. {NEED}")
            ),
            "{proto:?}"
        );
        assert_eq!(
            proto.err(&c, "CREATE SEQUENCE r2").await,
            e(
                "0A000",
                &format!("CREATE SEQUENCE is not supported without an explicit cache size. {NEED}")
            ),
            "{proto:?}"
        );
        for sql in [
            "CREATE SEQUENCE r3 CACHE 2",
            "CREATE SEQUENCE r3 CACHE 65535",
            "ALTER SEQUENCE r3 CACHE 100",
            "CREATE TABLE r4 (id bigint GENERATED ALWAYS AS IDENTITY (CACHE 100))",
        ] {
            assert_eq!(
                proto.err(&c, sql).await,
                e("0A000", "CACHE must be 1 or at least 65536"),
                "{proto:?}: {sql}"
            );
        }
        for (ty, shown) in [
            ("integer", "integer"),
            ("smallint", "smallint"),
            ("int", "integer"),
        ] {
            assert_eq!(
                proto
                    .err(
                        &c,
                        &format!(
                            "CREATE TABLE r5 (id {ty} GENERATED BY DEFAULT AS IDENTITY (CACHE 1))"
                        )
                    )
                    .await,
                e(
                    "0A000",
                    &format!("datatype {shown} not supported, identity column type must be bigint")
                ),
                "{proto:?}: {ty}"
            );
        }
        // Nothing was created by the refusals.
        assert_eq!(sequences(&c, "r1_id_seq").await, s("0"));
        assert_eq!(sequences(&c, "r3").await, s("0"));
    }
}

#[tokio::test]
async fn an_identity_create_table_is_one_ddl_and_leaves_nothing_when_it_fails() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let t = format!("one_{proto:?}").to_lowercase();
        // Inside a transaction the CREATE TABLE (a sequence and a table) is the one DDL.
        proto.ok(&c, "BEGIN").await;
        proto
            .ok(
                &c,
                &format!(
                    "CREATE TABLE {t} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY)"
                ),
            )
            .await;
        assert_eq!(
            proto.err(&c, &format!("CREATE TABLE {t}_b (id int)")).await,
            e(
                "0A000",
                "multiple ddl statements not supported in a transaction"
            ),
            "{proto:?}"
        );
        proto.ok(&c, "ROLLBACK").await;
        assert_eq!(sequences(&c, &format!("{t}_id_seq")).await, s("0"));
        // A CREATE TABLE that fails in the engine after the sequence was made leaves no sequence:
        // outside a transaction (compensated) and inside one (rolled back).
        let bad = format!("{t}_bad");
        let ddl = format!(
            "CREATE TABLE {bad} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1), x no_such_type)"
        );
        proto.err(&c, &ddl).await;
        assert_eq!(
            sequences(&c, &format!("{bad}_id_seq")).await,
            s("0"),
            "{proto:?}"
        );
        proto.ok(&c, "BEGIN").await;
        proto.err(&c, &ddl).await;
        proto.ok(&c, "ROLLBACK").await;
        assert_eq!(
            sequences(&c, &format!("{bad}_id_seq")).await,
            s("0"),
            "{proto:?}"
        );
        // An existing table's sequence survives a failed re-create.
        proto
            .ok(
                &c,
                &format!(
                    "CREATE TABLE {t}_k (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY)"
                ),
            )
            .await;
        assert!(proto
            .run(
                &c,
                &format!(
                    "CREATE TABLE {t}_k (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY)"
                )
            )
            .await
            .is_err());
        assert_eq!(
            sequences(&c, &format!("{t}_k_id_seq")).await,
            s("1"),
            "{proto:?}"
        );
    }
}

#[tokio::test]
async fn dropping_a_table_drops_its_identity_sequences() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let t = format!("drp_{proto:?}").to_lowercase();
        let create = format!(
            "CREATE TABLE {t} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY, v text)"
        );
        proto.ok(&c, &create).await;
        assert_eq!(
            column(
                proto,
                &c,
                &format!("INSERT INTO {t} (v) VALUES ('a'), ('b') RETURNING id")
            )
            .await,
            ["1", "2"]
        );
        assert_eq!(sequences(&c, &format!("{t}_id_seq")).await, s("1"));
        proto.ok(&c, &format!("DROP TABLE {t}")).await;
        assert_eq!(
            sequences(&c, &format!("{t}_id_seq")).await,
            s("0"),
            "{proto:?}"
        );
        // Created again with the same definition: numbering restarts.
        proto.ok(&c, &create).await;
        assert_eq!(
            column(
                proto,
                &c,
                &format!("INSERT INTO {t} (v) VALUES ('a') RETURNING id")
            )
            .await,
            ["1"],
            "{proto:?}"
        );
        // A sequence that is not an identity's stays: only `<table>_<column>_seq` defaults go.
        let other = format!("{t}_keep");
        proto
            .ok(&c, &format!("CREATE SEQUENCE {other}_seq CACHE 1"))
            .await;
        proto
            .ok(
                &c,
                &format!(
                    "CREATE TABLE {other} (id bigint PRIMARY KEY DEFAULT nextval('{other}_seq'))"
                ),
            )
            .await;
        proto.ok(&c, &format!("DROP TABLE {other}")).await;
        assert_eq!(
            sequences(&c, &format!("{other}_seq")).await,
            s("1"),
            "{proto:?}"
        );
    }
}

use crate::dsql_rules::ABORTED;

async fn column_exists(c: &Client, table: &str, column: &str) -> bool {
    value(
        c,
        &format!(
            "SELECT count(*) FROM pg_attribute a JOIN pg_class t ON t.oid = a.attrelid \
             WHERE t.relname = '{table}' AND a.attname = '{column}' AND a.attnum > 0"
        ),
    )
    .await
        == s("1")
}

#[tokio::test]
async fn alter_table_forms_dsql_refuses() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let t = format!("alt_{proto:?}").to_lowercase();
        proto
            .ok(
                &c,
                &format!("CREATE TABLE {t} (id int PRIMARY KEY, w int, v text)"),
            )
            .await;
        for (i, column) in [
            "d int DEFAULT 0",
            "d int NOT NULL",
            "d int CHECK (d > 0)",
            "d int UNIQUE",
            "d int PRIMARY KEY",
            "d int REFERENCES alt_target (id)",
            "d bigint GENERATED ALWAYS AS IDENTITY (CACHE 1)",
        ]
        .into_iter()
        .enumerate()
        {
            assert_eq!(
                proto
                    .err(&c, &format!("ALTER TABLE {t} ADD COLUMN {column}"))
                    .await,
                e(
                    "0A000",
                    "ALTER TABLE ADD COLUMN with constraint not supported"
                ),
                "{proto:?} {i}"
            );
        }
        assert!(!column_exists(&c, &t, "d").await, "{proto:?}");
        // A plain column, with or without IF NOT EXISTS and with a bare numeric, still works.
        proto
            .ok(&c, &format!("ALTER TABLE {t} ADD COLUMN d text"))
            .await;
        // (`ADD COLUMN IF NOT EXISTS` passes the M3 rules; the engine itself refuses it: known gap.)
        proto
            .ok(&c, &format!("ALTER TABLE {t} ADD COLUMN n numeric"))
            .await;
        assert!(column_exists(&c, &t, "d").await);
        assert_eq!(
            proto
                .err(&c, &format!("ALTER TABLE {t} ALTER COLUMN w TYPE bigint"))
                .await,
            e(
                "0A000",
                "unsupported ALTER TABLE ALTER COLUMN ... SET DATA TYPE statement"
            ),
            "{proto:?}"
        );
        assert_eq!(
            proto
                .err(&c, &format!("ALTER TABLE {t} ALTER COLUMN w SET NOT NULL"))
                .await,
            e(
                "0A000",
                "SET NOT NULL is not supported (only DROP NOT NULL)"
            ),
            "{proto:?}"
        );
        // A refusal inside a transaction aborts it.
        proto.ok(&c, "BEGIN").await;
        assert_eq!(
            proto
                .err(&c, &format!("ALTER TABLE {t} ADD COLUMN z int DEFAULT 1"))
                .await
                .code,
            "0A000"
        );
        assert_eq!(
            proto.err(&c, "SELECT 1").await,
            e("25P02", ABORTED),
            "{proto:?}"
        );
        proto.ok(&c, "ROLLBACK").await;
    }
}

#[tokio::test]
async fn dropping_a_primary_key_column_is_refused() {
    let server = TestServer::start();
    let c = server.connect().await;
    for proto in PROTOS {
        let t = format!("pk_{proto:?}").to_lowercase();
        proto
            .ok(
                &c,
                &format!("CREATE TABLE {t} (id int PRIMARY KEY, v text)"),
            )
            .await;
        proto
            .ok(
                &c,
                &format!("CREATE TABLE {t}_c (a int, b int, v text, PRIMARY KEY (a, b))"),
            )
            .await;
        assert_eq!(
            proto
                .err(&c, &format!("ALTER TABLE {t} DROP COLUMN id"))
                .await,
            e("0A000", "cannot drop primary key column id"),
            "{proto:?}"
        );
        assert_eq!(
            proto
                .err(
                    &c,
                    &format!("ALTER TABLE {t}_c DROP COLUMN v, DROP COLUMN b")
                )
                .await,
            e("0A000", "cannot drop primary key column b"),
            "{proto:?}"
        );
        assert!(column_exists(&c, &t, "id").await);
        assert!(column_exists(&c, &format!("{t}_c"), "v").await, "{proto:?}");
        // A non-key column can still be dropped.
        proto
            .ok(&c, &format!("ALTER TABLE {t} DROP COLUMN v"))
            .await;
        assert!(!column_exists(&c, &t, "v").await);
        // The refusal aborts a transaction like every other refusal.
        proto.ok(&c, "BEGIN").await;
        assert_eq!(
            proto
                .err(&c, &format!("ALTER TABLE {t} DROP COLUMN id"))
                .await,
            e("0A000", "cannot drop primary key column id")
        );
        assert_eq!(
            proto.err(&c, "SELECT 1").await,
            e("25P02", ABORTED),
            "{proto:?}"
        );
        proto.ok(&c, "ROLLBACK").await;
        proto.ok(&c, &format!("SELECT * FROM {t}")).await;
    }
}
