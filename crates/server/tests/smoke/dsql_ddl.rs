// --- Table rebuild for NOT VALID constraints (FR-024, research.md D13) --------------------

/// `name -> definition` of every constraint of a table, sorted.
async fn constraints_of(c: &Client, table: &str) -> Vec<String> {
    rows(
        c,
        &format!(
            "SELECT co.conname || ' ' || pg_get_constraintdef(co.oid) FROM pg_constraint co \
             JOIN pg_class t ON t.oid = co.conrelid WHERE t.relname = '{table}' ORDER BY 1"
        ),
    )
    .await
    .into_iter()
    .map(|r| r[0].clone().unwrap_or_default())
    .collect()
}

async fn indexes_of(c: &Client, table: &str) -> Vec<String> {
    rows(
        c,
        &format!(
            "SELECT indexname FROM pg_indexes WHERE tablename = '{table}' \
             AND indexname NOT LIKE '%turso_internal%' AND indexname NOT LIKE 'sqlite_autoindex%' ORDER BY 1"
        ),
    )
    .await
    .into_iter()
    .map(|r| r[0].clone().unwrap_or_default())
    .collect()
}

async fn rebuild_fixture(c: &Client, p: &str, t: &str, g: &str) {
    for sql in [
        format!("CREATE TABLE {p} (id bigint PRIMARY KEY)"),
        format!(
            "CREATE TABLE {t} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) PRIMARY KEY, \
             code text NOT NULL DEFAULT 'x', w int UNIQUE, n numeric(10,2), \
             u uuid DEFAULT gen_random_uuid(), j jsonb, ts timestamptz DEFAULT now(), \
             v varchar(255), parent bigint, other bigint REFERENCES {p} (id), \
             CONSTRAINT {t}_w_check CHECK (w IS NULL OR w < 1000))"
        ),
        format!("CREATE TABLE {g} (id int PRIMARY KEY, cid bigint REFERENCES {t} (id) ON DELETE CASCADE)"),
    ] {
        c.simple_query(&sql).await.unwrap();
    }
    c.simple_query(&format!("INSERT INTO {p} VALUES (1)"))
        .await
        .unwrap();
    for (name, ddl) in [
        ("s", format!("CREATE INDEX ASYNC {t}_s ON {t} (code)")),
        (
            "part",
            format!("CREATE INDEX ASYNC {t}_part ON {t} (w) WHERE w > 1"),
        ),
        (
            "expr",
            format!("CREATE INDEX ASYNC {t}_expr ON {t} ((lower(code)))"),
        ),
        (
            "uq",
            format!("CREATE UNIQUE INDEX ASYNC {t}_uq ON {t} (code, w)"),
        ),
    ] {
        let id = job_id(c, &ddl).await;
        assert_eq!(succeeded(c, &id).await, "t", "{name}");
    }
    c.simple_query(&format!(
        "INSERT INTO {t} (w, n, v, parent, other) VALUES (1, 1.50, 'a', 99, 1), (2, 2.25, 'b', 1, NULL)"
    ))
    .await
    .unwrap();
    c.simple_query(&format!("INSERT INTO {g} VALUES (1, 1), (2, 2)"))
        .await
        .unwrap();
}

#[tokio::test]
async fn a_rebuild_keeps_the_table_whole() {
    let server = TestServer::start();
    let c = server.connect().await;
    let (p, t, g) = ("rbp", "rbt", "rbg");
    rebuild_fixture(&c, p, t, g).await;
    let before_constraints = constraints_of(&c, t).await;
    let before_indexes = indexes_of(&c, t).await;
    let before_gc = constraints_of(&c, g).await;
    assert_eq!(before_indexes.len(), 4, "{before_indexes:?}");
    let before_rows = rows(&c, &format!("SELECT * FROM {t} ORDER BY id")).await;
    // `parent` = 99 is an orphan: NOT VALID leaves it alone.
    c.simple_query(&format!(
        "ALTER TABLE {t} ADD CONSTRAINT {t}_parent_fk FOREIGN KEY (parent) REFERENCES {t} (id) \
         ON DELETE CASCADE NOT VALID"
    ))
    .await
    .unwrap();
    assert_eq!(
        rows(&c, &format!("SELECT * FROM {t} ORDER BY id")).await,
        before_rows
    );
    // Same constraints (plus the new one), same indexes, same referencing constraint.
    let mut expected = before_constraints.clone();
    let after = constraints_of(&c, t).await;
    assert_eq!(after.len(), expected.len() + 1, "{after:?}");
    expected.retain(|c| after.contains(c));
    assert_eq!(
        expected.len(),
        before_constraints.len(),
        "{before_constraints:?} vs {after:?}"
    );
    assert!(
        after
            .iter()
            .any(|c| c.starts_with(&format!("{t}_parent_fk FOREIGN KEY"))),
        "{after:?}"
    );
    assert_eq!(indexes_of(&c, t).await, before_indexes);
    assert_eq!(constraints_of(&c, g).await, before_gc);
    // Identity continues where it was; defaults still apply.
    assert_eq!(
        value(
            &c,
            &format!("INSERT INTO {t} (w, v) VALUES (10, 'c') RETURNING id")
        )
        .await,
        s("3")
    );
    assert_eq!(
        value(&c, &format!("SELECT code FROM {t} WHERE id = 3")).await,
        s("x")
    );
    assert_eq!(
        value(
            &c,
            &format!("SELECT count(*) FROM {t} WHERE u IS NOT NULL AND ts IS NOT NULL")
        )
        .await,
        s("3")
    );
    // The new constraint and the old ones are enforced; so is the referencing table's.
    assert_eq!(
        crate::common::simple_err(
            &c,
            &format!("INSERT INTO {t} (w, parent) VALUES (11, 12345)")
        )
        .await
        .code,
        "23503"
    );
    assert_eq!(
        crate::common::simple_err(&c, &format!("INSERT INTO {t} (w, other) VALUES (12, 777)"))
            .await
            .code,
        "23503"
    );
    assert_eq!(
        crate::common::simple_err(&c, &format!("INSERT INTO {t} (w) VALUES (1)"))
            .await
            .code,
        "23505"
    );
    assert_eq!(
        crate::common::simple_err(&c, &format!("INSERT INTO {t} (w) VALUES (5000)"))
            .await
            .code,
        "23514"
    );
    assert_eq!(
        crate::common::simple_err(&c, &format!("INSERT INTO {g} VALUES (9, 424242)"))
            .await
            .code,
        "23503"
    );
    c.simple_query(&format!("DELETE FROM {t} WHERE id = 2"))
        .await
        .unwrap();
    assert_eq!(
        value(&c, &format!("SELECT count(*) FROM {g} WHERE cid = 2")).await,
        s("0"),
        "ON DELETE CASCADE of the referencing table"
    );
    // The jobs of the ASYNC indexes still point at their (recreated) indexes.
    assert_eq!(
        value(
            &c,
            &format!(
                "SELECT count(*) FROM sys.jobs j JOIN pg_class i ON i.oid = j.object_id \
                 WHERE j.object_name = 'public.{t}_s' AND i.relname = '{t}_s'"
            )
        )
        .await,
        s("1")
    );
    // VALIDATE finds the constraint, and fails for the orphan.
    let id = job_id(
        &c,
        &format!("ALTER TABLE ASYNC {t} VALIDATE CONSTRAINT {t}_parent_fk"),
    )
    .await;
    assert_eq!(succeeded(&c, &id).await, "f");
    // DROP TABLE still removes the identity sequence.
    assert_eq!(sequences(&c, &format!("{t}_id_seq")).await, s("1"));
    c.simple_query(&format!("DROP TABLE {g}")).await.unwrap();
    c.simple_query(&format!("DROP TABLE {t}")).await.unwrap();
    assert_eq!(sequences(&c, &format!("{t}_id_seq")).await, s("0"));
}

#[tokio::test]
async fn a_rebuild_is_one_ddl_and_follows_the_transaction() {
    let server = TestServer::start();
    let c = server.connect().await;
    rebuild_fixture(&c, "rtp", "rtt", "rtg").await;
    let add = "ALTER TABLE rtt ADD CONSTRAINT rtt_parent_fk FOREIGN KEY (parent) REFERENCES rtp (id) NOT VALID";
    c.simple_query("BEGIN").await.unwrap();
    c.simple_query(add).await.unwrap();
    assert_eq!(
        crate::common::simple_err(&c, "CREATE TABLE rt_other (id int)").await,
        e(
            "0A000",
            "multiple ddl statements not supported in a transaction"
        )
    );
    c.simple_query("ROLLBACK").await.unwrap();
    // Rolled back: no constraint, the orphan can be written, indexes and rows are as before.
    assert!(!constraints_of(&c, "rtt")
        .await
        .iter()
        .any(|x| x.starts_with("rtt_parent_fk")));
    c.simple_query("INSERT INTO rtt (w, parent) VALUES (20, 424242)")
        .await
        .unwrap();
    assert_eq!(indexes_of(&c, "rtt").await.len(), 4);
    c.simple_query("DELETE FROM rtt WHERE w = 20")
        .await
        .unwrap();
    c.simple_query("BEGIN").await.unwrap();
    c.simple_query(add).await.unwrap();
    c.simple_query("COMMIT").await.unwrap();
    assert!(constraints_of(&c, "rtt")
        .await
        .iter()
        .any(|x| x.starts_with("rtt_parent_fk")));
    // Enforcement is back on for the session's later statements (foreign keys and CHECK).
    assert_eq!(
        crate::common::simple_err(&c, "INSERT INTO rtt (w, parent) VALUES (21, 424242)")
            .await
            .code,
        "23503"
    );
    assert_eq!(
        crate::common::simple_err(&c, "INSERT INTO rtt (w) VALUES (5000)")
            .await
            .code,
        "23514"
    );
}

