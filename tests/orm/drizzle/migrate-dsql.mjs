// Applies the Drizzle migrations the way DSQL requires: one DDL statement per transaction, no DDL
// and DML together, and a wait on every job a statement starts. Drizzle's stock migrator cannot
// do this (it creates its journal with SERIAL and runs everything in one transaction), which is
// why this runner exists; it reads the same migration files through drizzle-orm's own reader.
import { readMigrationFiles } from "drizzle-orm/migrator";
import { connect, describe, migrationsFolder } from "./lib.mjs";

const JOURNAL = "drizzle.__drizzle_migrations_dsql";

const client = await connect();

/** Runs one statement in its own transaction; waits for the job it starts, if any. */
async function runStatement(sql, params) {
  await client.query("BEGIN");
  let result;
  try {
    result = await client.query(sql, params);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    throw error;
  }
  const jobId = result.rows?.[0]?.job_id;
  if (jobId) {
    const wait = await client.query("CALL sys.wait_for_job($1)", [jobId]);
    if (wait.rows[0]?.succeeded !== true) {
      const job = await client.query("SELECT status, details FROM sys.jobs WHERE job_id = $1", [jobId]);
      throw new Error(`job ${jobId} did not succeed: ${JSON.stringify(job.rows[0])}`);
    }
    return `job ${jobId} succeeded`;
  }
  return result.command ?? "OK";
}

try {
  await runStatement("CREATE SCHEMA IF NOT EXISTS drizzle");
  await runStatement(
    `CREATE TABLE IF NOT EXISTS ${JOURNAL} (id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 65536) PRIMARY KEY, hash text NOT NULL, created_at bigint)`,
  );
  const applied = new Set((await client.query(`SELECT hash FROM ${JOURNAL}`)).rows.map((r) => r.hash));
  let count = 0;
  for (const migration of readMigrationFiles({ migrationsFolder })) {
    if (applied.has(migration.hash)) continue;
    console.log(`migration ${migration.hash.slice(0, 12)}: ${migration.sql.length} statement(s)`);
    for (const statement of migration.sql) {
      const summary = statement.replace(/\s+/g, " ").trim().slice(0, 90);
      const outcome = await runStatement(statement);
      console.log(`  ${outcome.padEnd(36)} | ${summary}`);
    }
    await runStatement(`INSERT INTO ${JOURNAL} (hash, created_at) VALUES ($1, $2)`, [
      migration.hash,
      migration.folderMillis,
    ]);
    count += 1;
  }
  console.log(`applied ${count} migration(s)`);
} catch (error) {
  console.error(`MIGRATE FAILED: ${describe(error)}`);
  process.exitCode = 1;
} finally {
  await client.end();
}
