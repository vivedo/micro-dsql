#!/bin/sh
# Differential run (T1 layer 2): run tests/psql/run.sh --all (layer-1 scenarios and
# DSQL-rule probes) against two targets and write reports/diff-<YYYY-MM-DD>.md.
#
# Targets are described either by environment variables
#   TARGET_A_HOST TARGET_A_PORT [TARGET_A_USER TARGET_A_DATABASE TARGET_A_PASSWORD
#   TARGET_A_SSLMODE TARGET_A_NAME]   (and the same with TARGET_B_)
# or by env files that set PG* variables (and optionally NAME):
#   scripts/compare.sh --a micro-dsql.env --b ministack.env
# Defaults: A is "micro-dsql" at 127.0.0.1:15432, B is "ministack" at
# localhost:25432; user admin, database postgres, any password, sslmode=disable.
#
# Optional: REPORT_DIR (default reports/), REPORT_FILE (default
# $REPORT_DIR/diff-<date>.md).
#
# A target that cannot be reached is reported as unreachable; the report is still
# written. Exit status: 0 when the report was written, 2 on usage errors.

set -u

root=$(cd "$(dirname "$0")/.." && pwd)
runner="$root/tests/psql/run.sh"

a_env=""; b_env=""
while [ $# -gt 0 ]; do
    case $1 in
        --a) a_env=$2; shift ;;
        --b) b_env=$2; shift ;;
        -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
        *) echo "compare.sh: unknown argument $1" >&2; exit 2 ;;
    esac
    shift
done
for f in "$a_env" "$b_env"; do
    [ -z "$f" ] || [ -f "$f" ] || { echo "compare.sh: env file $f not found" >&2; exit 2; }
done

report_dir=${REPORT_DIR:-$root/reports}
mkdir -p "$report_dir" || exit 2
day=$(date +%Y-%m-%d)
report=${REPORT_FILE:-$report_dir/diff-$day.md}

work=$(mktemp -d "${TMPDIR:-/tmp}/t1-compare.XXXXXX") || exit 2
trap 'rm -rf "$work"' EXIT INT TERM

# run_target <slot A|B> <env file or empty>
run_target() {
    slot=$1; envfile=$2
    mkdir -p "$work/$slot"
    (
        unset PGHOST PGPORT PGUSER PGDATABASE PGPASSWORD PGSSLMODE PGSERVICE PGOPTIONS NAME
        if [ -n "$envfile" ]; then
            # shellcheck disable=SC1090
            . "$envfile"
        else
            eval "PGHOST=\${TARGET_${slot}_HOST:-}; PGPORT=\${TARGET_${slot}_PORT:-}"
            eval "PGUSER=\${TARGET_${slot}_USER:-admin}; PGDATABASE=\${TARGET_${slot}_DATABASE:-postgres}"
            eval "PGPASSWORD=\${TARGET_${slot}_PASSWORD:-anything}; PGSSLMODE=\${TARGET_${slot}_SSLMODE:-disable}"
            eval "NAME=\${TARGET_${slot}_NAME:-}"
        fi
        if [ "$slot" = A ]; then
            : "${NAME:=micro-dsql}" "${PGHOST:=127.0.0.1}" "${PGPORT:=15432}"
        else
            : "${NAME:=ministack}" "${PGHOST:=localhost}" "${PGPORT:=25432}"
        fi
        : "${PGUSER:=admin}" "${PGDATABASE:=postgres}" "${PGPASSWORD:=anything}" "${PGSSLMODE:=disable}"
        export PGHOST PGPORT PGUSER PGDATABASE PGPASSWORD PGSSLMODE
        printf '%s\n' "$NAME" > "$work/$slot/name"
        printf '%s:%s\n' "$PGHOST" "$PGPORT" > "$work/$slot/endpoint"
        RESULTS_DIR="$work/$slot" "$runner" --all > "$work/$slot/run.log" 2>&1
        echo $? > "$work/$slot/exit"
    )
}

echo "compare.sh: running target A" >&2
run_target A "$a_env"
echo "compare.sh: running target B" >&2
run_target B "$b_env"

name_a=$(cat "$work/A/name"); name_b=$(cat "$work/B/name")

field() {  # slot key  (from target.txt)
    sed -n "s/^$2	//p" "$work/$1/target.txt" 2>/dev/null
}
status_of() {  # slot name
    if [ "$(field "$1" status)" != reachable ]; then echo unreachable; return; fi
    s=$(awk -F'	' -v n="$2" '$2 == n { print $3 }' "$work/$1/results.tsv" 2>/dev/null)
    echo "${s:-not run}"
}
strip_diff_header() { sed -e '1{/^--- /d;}' -e '1{/^+++ /d;}'; }

items() {  # kind<TAB>name for every scenario and probe in the repository
    for f in "$root"/tests/psql/[0-9][0-9]_*.sql "$root"/tests/psql/[0-9][0-9]_*.sh; do
        [ -f "$f" ] && b=${f##*/} && printf 'scenario\t%s\n' "${b%.*}"
    done | sort
    for f in "$root"/tests/psql/probes/[0-9][0-9]_*.sql; do
        [ -f "$f" ] && b=${f##*/} && printf 'probe\t%s\n' "${b%.*}"
    done | sort
}

{
    echo "# Differential report $day"
    echo
    echo "Generated by \`scripts/compare.sh\`. Scenarios are blocking (PASS/FAIL against"
    echo "\`tests/psql/expected\`); probes are report-only (MATCH/DIFFER against the reference"
    echo "output in \`tests/psql/probes/expected\`, captured from MiniStack with \`DSQL_STRICT=1\`)."
    echo
    echo "## Targets"
    echo
    echo "| slot | name | endpoint | reachable | server_version | run.sh summary |"
    echo "|---|---|---|---|---|---|"
    for slot in A B; do
        reach=$(field "$slot" status); [ -n "$reach" ] || reach=unknown
        summary=$(sed -n 's/^summary: //p' "$work/$slot/run.log" | tail -1)
        printf '| %s | %s | %s | %s | %s | %s |\n' "$slot" "$(cat "$work/$slot/name")" \
            "$(cat "$work/$slot/endpoint")" "$reach" "$(field "$slot" server_version)" "${summary:--}"
    done
    for slot in A B; do
        if [ "$(field "$slot" status)" != reachable ]; then
            echo
            echo "Target $slot ($(cat "$work/$slot/name")) is **unreachable**:"
            echo
            echo '```'
            cat "$work/$slot/run.log"
            echo '```'
        fi
    done
    echo
    echo "## Results"
    echo
    echo "| item | kind | $name_a (A) | $name_b (B) | same output |"
    echo "|---|---|---|---|---|"
    items | while IFS='	' read -r kind name; do
        sa=$(status_of A "$name"); sb=$(status_of B "$name")
        if [ -f "$work/A/$name.out" ] && [ -f "$work/B/$name.out" ]; then
            if cmp -s "$work/A/$name.out" "$work/B/$name.out"; then same=yes; else same='**no**'; fi
        else
            same=n/a
        fi
        printf '| %s | %s | %s | %s | %s |\n' "$name" "$kind" "$sa" "$sb" "$same"
    done
    echo
    echo "## Differences between A and B"
    echo
    items | while IFS='	' read -r kind name; do
        if [ -f "$work/A/$name.out" ] && [ -f "$work/B/$name.out" ] \
            && ! cmp -s "$work/A/$name.out" "$work/B/$name.out"; then
            echo "### $name ($kind)"
            echo
            echo "\`-\` = $name_a (A), \`+\` = $name_b (B)"
            echo
            echo '```diff'
            diff -u "$work/A/$name.out" "$work/B/$name.out" | strip_diff_header | strip_diff_header
            echo '```'
            echo
        fi
    done
    echo "## Failures against expected output"
    echo
    echo "Shown only where the A/B diff above does not already say it (that is, when the"
    echo "other target did not match the expected output either, or was unreachable)."
    echo
    for slot in A B; do
        if [ "$slot" = A ]; then other=B; else other=A; fi
        items | while IFS='	' read -r kind name; do
            st=$(status_of "$slot" "$name")
            case $(status_of "$other" "$name") in PASS|MATCH) continue ;; esac
            case $st in
                FAIL|DIFFER)
                    echo "### $name on $(cat "$work/$slot/name") ($slot): $st"
                    echo
                    echo "\`-\` = expected (reference), \`+\` = actual"
                    echo
                    echo '```diff'
                    strip_diff_header < "$work/$slot/$name.diff" | strip_diff_header
                    echo '```'
                    echo
                    ;;
            esac
        done
    done
    echo "## Backlog candidates (M2/M3)"
    echo
    echo "Probes on which $name_a (A) differs from the reference behaviour:"
    echo
    n=0
    for name in $(awk -F'	' '$1 == "probe" && $3 == "DIFFER" { print $2 }' "$work/A/results.tsv" 2>/dev/null); do
        echo "- [ ] \`$name\`: align with the reference (see its diff above)"
        n=$((n + 1))
    done
    [ "$n" -eq 0 ] && echo "- none (target A matched every probe, or was unreachable)"
    :
} > "$report"

echo "compare.sh: wrote $report" >&2
echo "$report"
exit 0
